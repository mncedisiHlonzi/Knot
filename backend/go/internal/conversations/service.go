// Service holds the conversation business rules.
//
// It depends on the CommentStore abstraction and a Notifier, and knows nothing
// about HTTP, JSON, or SQL.
type Service struct {
	comments CommentStore
	notifier Notifier
}

// NewService wires the comment store and a notifier into the conversations
// domain.
func NewService(comments CommentStore, notifier Notifier) (*Service, error) {
	if comments == nil {
		return nil, fmt.Errorf("conversations: service requires a comment store")
	}
	if notifier == nil {
		return nil, fmt.Errorf("conversations: service requires a notifier")
	}
	return &Service{comments: comments, notifier: notifier}, nil
}

// CreateComment validates the input, stores the comment, and returns it.
//
// A comment may name a parent, which makes it a reply. The parent must exist and
// belong to the same version, and threading is one level deep: a reply to a reply
// is stored against the reply's own parent, so a thread never nests further
// (KNOT-ADR-047).
//
// It returns a *ValidationError for bad input — including a parent that names no
// comment on this version — and ErrNotFound when the version does not exist (or the
// version id is not a UUID, so it cannot name a version).
func (s *Service) CreateComment(ctx context.Context, in CreateCommentInput) (Comment, error) {
	comment, err := validateCreateComment(in)
	if err != nil {
		return Comment{}, err
	}

	// A comment cannot name itself. The id is generated by the store, so this is
	// only reachable by a caller that supplies one, but the rule belongs beside the
	// database's CHECK rather than only in it (KNOT-ADR-047).
	if comment.ID != "" && comment.ParentCommentID != nil && *comment.ParentCommentID == comment.ID {
		return Comment{}, &ValidationError{Field: "parent_comment_id", Message: "must not name the comment itself"}
	}

	// The comment the reply is addressed to, captured before the depth limit
	// rewrites the parent. It is also who the notification goes to: whoever the
	// client replied to is the person who hears about it.
	var addressedTo *Comment
	if comment.ParentCommentID != nil {
		parent, err := s.resolveParent(ctx, comment.VersionID, *comment.ParentCommentID)
		if err != nil {
			return Comment{}, err
		}
		addressedTo = &parent

		// Depth limit: a reply to a reply hangs off the top-level comment that reply
		// belongs to, so the stored thread is never deeper than one level.
		if parent.ParentCommentID != nil {
			comment.ParentCommentID = parent.ParentCommentID
		}
	}

	// Block-based write prevention (KNOT-ADR-060): a user cannot comment on a
	// version, or reply to a comment, authored by someone on either side of a
	// block. The check is skipped entirely when the request carries no block set
	// (anonymous readers, and viewers who have blocked nobody), so the common case
	// costs no extra query.
	if len(moderation.ExcludedAuthors(ctx)) > 0 {
		versionAuthor, err := s.comments.VersionAuthor(ctx, comment.VersionID)
		if err != nil {
			if errors.Is(err, ErrNotFound) {
				return Comment{}, ErrNotFound
			}
			return Comment{}, fmt.Errorf("conversations: resolve version author: %w", err)
		}
		if moderation.IsExcludedAuthor(ctx, versionAuthor) {
			return Comment{}, moderation.ErrBlocked
		}
		if addressedTo != nil && moderation.IsExcludedAuthor(ctx, addressedTo.AuthorID) {
			return Comment{}, moderation.ErrBlocked
		}
	}

	created, err := s.comments.CreateComment(ctx, comment)
	if err != nil {
		if errors.Is(err, ErrNotFound) {
			return Comment{}, ErrNotFound
		}
		return Comment{}, fmt.Errorf("conversations: create comment: %w", err)
	}

	s.notifyCommentCreated(ctx, created, addressedTo)

	return created, nil
}

// resolveParent loads the comment a reply names and refuses one that cannot be a
// parent of a comment on versionID.
//
// A parent that does not exist, or that belongs to another version, is a
// validation error on parent_comment_id rather than a 404: the version in the path
// was found, so the field is what the client has to change.
func (s *Service) resolveParent(ctx context.Context, versionID, parentID string) (Comment, error) {
	parent, err := s.comments.GetComment(ctx, parentID)
	if err != nil {
		if errors.Is(err, ErrNotFound) {
			return Comment{}, &ValidationError{
				Field:   "parent_comment_id",
				Message: "must name a comment on the version being commented on",
			}
		}
		return Comment{}, fmt.Errorf("conversations: load parent comment: %w", err)
	}

	if parent.VersionID != versionID {
		return Comment{}, &ValidationError{
			Field:   "parent_comment_id",
			Message: "must name a comment on the version being commented on",
		}
	}

	return parent, nil
}

// notifyCommentCreated tells the author of the comment that was replied to — or of
// the version, when the comment is top-level — that someone wrote a comment.
//
// The recipient is whoever the client addressed, which for a reply to a reply is
// the author of that reply rather than of the thread's top-level comment: they are
// the person the client replied to. Acting on your own comment, or commenting on
// your own version, never notifies you (KNOT-ADR-038).
//
// A notification is a side effect. A lookup failure or a failed notification is
// ignored here, because the comment has already been stored and must not be lost
// (KNOT-ADR-038).
func (s *Service) notifyCommentCreated(ctx context.Context, comment Comment, parent *Comment) {
	var recipientID string

	if parent != nil {
		recipientID = parent.AuthorID
	} else {
		authorID, err := s.comments.VersionAuthor(ctx, comment.VersionID)
		if err != nil {
			return
		}
		recipientID = authorID
	}

	if recipientID == comment.AuthorID {
		return
	}
	_ = s.notifier.NotifyCommentCreated(ctx, recipientID, comment.AuthorID, comment.ID)
}

// ListComments returns one page of a version's thread, plus the cursor that
// resumes after it.
//
// A page is ordered for reading top to bottom: each top-level comment, newest
// first, followed by its own replies oldest first. limit counts top-level
// comments, so a page returns more rows than limit when comments have replies
// (KNOT-ADR-047).
//
// An empty rawCursor asks for the first page. The returned next cursor is the
// empty string when the page is the last one. A version that does not exist is
// reported as ErrNotFound.
func (s *Service) ListComments(ctx context.Context, versionID string, rawCursor string, limit int) ([]Comment, string, error) {
	if !isUUID(versionID) {
		return nil, "", ErrNotFound
	}
	if limit < 1 || limit > MaxListLimit {
		return nil, "", &ValidationError{
			Field:   "limit",
			Message: fmt.Sprintf("must be between 1 and %d", MaxListLimit),
		}
	}

	var cursor *Cursor
	if rawCursor != "" {
		decoded, err := DecodeCursor(rawCursor)
		if err != nil {
			return nil, "", err
		}
		cursor = &decoded
	}

	page, next, err := s.comments.ListComments(ctx, versionID, cursor, limit)
	if err != nil {
		if errors.Is(err, ErrNotFound) {
			return nil, "", ErrNotFound
		}
		return nil, "", fmt.Errorf("conversations: list comments: %w", err)
	}

	if page == nil {
		// Emit [] rather than null so a client never has to special-case an
		// empty thread.
		page = []Comment{}
	}

	thread, err := s.attachReplies(ctx, page)
	if err != nil {
		return nil, "", err
	}

	nextCursor := ""
	if next != nil {
		nextCursor = next.Encode()
	}

	return thread, nextCursor, nil
}

// attachReplies returns a page of top-level comments as a thread: each comment
// followed by its own replies, oldest first. The page's own order — newest first —
// is preserved between threads.
//
// The replies are fetched for the whole page in one query, so a thread of any size
// costs two queries and a reply is never rendered detached from its parent.
func (s *Service) attachReplies(ctx context.Context, parents []Comment) ([]Comment, error) {
	if len(parents) == 0 {
		return parents, nil
	}

	ids := make([]string, 0, len(parents))
	for _, parent := range parents {
		ids = append(ids, parent.ID)
	}

	replies, err := s.comments.ListReplies(ctx, ids)
	if err != nil {
		return nil, fmt.Errorf("conversations: list replies: %w", err)
	}

	byParent := make(map[string][]Comment, len(parents))
	for _, reply := range replies {
		if reply.ParentCommentID == nil {
			continue
		}
		byParent[*reply.ParentCommentID] = append(byParent[*reply.ParentCommentID], reply)
	}

	thread := make([]Comment, 0, len(parents)+len(replies))
	for _, parent := range parents {
		thread = append(thread, parent)
		thread = append(thread, byParent[parent.ID]...)
	}

	return thread, nil
}

// GetComment returns a single comment by id, with the id of the story its version
// belongs to resolved (Comment.StoryID).
//
// It is how a notification tap resolves a comment id to the thread it belongs to:
// the version and the story come back together, so the client needs no second
// lookup.
//
// An id that is not canonical UUID text is reported as ErrNotFound rather than as
// a validation error: the resource genuinely does not exist, and answering 404
// keeps the id column's index usable instead of casting it to text in SQL.
func (s *Service) GetComment(ctx context.Context, id string) (Comment, error) {
	if !isUUID(id) {
		return Comment{}, ErrNotFound
	}

	comment, err := s.comments.GetComment(ctx, id)
	if err != nil {
		if errors.Is(err, ErrNotFound) {
			return Comment{}, ErrNotFound
		}
		return Comment{}, fmt.Errorf("conversations: get comment: %w", err)
	}

	// A detail view of a blocked author's comment is not found (KNOT-ADR-064).
	if moderation.IsExcludedAuthor(ctx, comment.AuthorID) {
		return Comment{}, ErrNotFound
	}

	return comment, nil
}

// validateCreateComment applies every input rule and returns the comment to store.
//
// The body is stored verbatim so the author's formatting survives; it is only
// trimmed to decide whether it is empty.
func validateCreateComment(in CreateCommentInput) (Comment, error) {
	// A version id from the request path that is not a UUID cannot name a
	// version, so it is reported as not-found rather than as a validation error.
	if !isUUID(in.VersionID) {
		return Comment{}, ErrNotFound
	}

	if !isUUID(in.AuthorID) {
		return Comment{}, &ValidationError{Field: "author_id", Message: "must be a UUID"}
	}

	language, err := validateLanguage(in.Language, "language")
	if err != nil {
		return Comment{}, err
	}

	body, err := validateBody(in.Body)
	if err != nil {
		return Comment{}, err
	}

	return Comment{
		VersionID:       in.VersionID,
		AuthorID:        in.AuthorID,
		Language:        language,
		Body:            body,
		ParentCommentID: in.ParentCommentID,
	}, nil
}

// validateBody requires a non-empty body within MaxBodyLen runes and returns it
// verbatim.
func validateBody(raw string) (string, error) {
	if utf8.RuneCountInString(strings.TrimSpace(raw)) < minBodyLen {
		return "", &ValidationError{Field: "body", Message: "is required"}
	}
	if utf8.RuneCountInString(raw) > MaxBodyLen {
		return "", &ValidationError{
			Field:   "body",
			Message: fmt.Sprintf("must be at most %d characters", MaxBodyLen),
		}
	}
	return raw, nil
}

// validateLanguage requires a canonical ISO 639-3 code, reporting a failure
// against the given field name.
//
// The code must match exactly: "eng" is accepted, while "ENG" and "en" are
// rejected, so a comment's language is always a known code (KNOT-ADR-046).
func validateLanguage(raw, field string) (string, error) {
	code := strings.TrimSpace(raw)
	if !language.IsValid(code) {
		return "", &ValidationError{
			Field:   field,
			Message: "must be a valid ISO 639-3 language code, such as eng or zul",
		}
	}
	return code, nil
}
